import React from 'react';
import { act, cleanup, render, screen, waitFor } from '@testing-library/react';
import { MemoryRouter, Route, Routes } from 'react-router-dom';
import { afterEach, beforeAll, beforeEach, describe, expect, it, vi } from 'vitest';
import fixtureData from './fixtures/trackingLocationProvenance.json';

// Client, page, TrackingMap and point/role normalization are real.
// Only public HTTP/identity/status envelope and the map renderer engine are synthetic.
const seam = vi.hoisted(() => ({ apiFetch: vi.fn(), markers: [] as Array<any>, maps: [] as Array<any> }));
vi.mock('@/utils/api', () => ({ apiFetch: (...args: unknown[]) => seam.apiFetch(...args),
  getErrorMessage: (error: unknown) => error instanceof Error ? error.message : 'Error sintético' }));
vi.mock('@/config', () => ({ getSocketUrl: () => { throw new Error('unexpected fixture socket config'); },
  SOCKET_PATH: '/socket.io' }));
vi.mock('socket.io-client', () => ({ io: () => { throw new Error('unexpected fixture socket'); } }));
vi.mock('maplibre-gl', () => {
  class Popup { text = ''; setText(value: string) { this.text = value; return this; } }
  class Marker {
    element: HTMLElement; position: number[] = []; popup?: Popup; removed = false;
    constructor({ element }: { element: HTMLElement }) { this.element = element; seam.markers.push(this); }
    setLngLat(value: number[]) { this.position = [...value]; return this; }
    setPopup(value: Popup) { this.popup = value; return this; }
    getPopup() { return this.popup; } addTo() { return this; } remove() { this.removed = true; }
  }
  class Map { constructor(options: unknown) { seam.maps.push(options); }
    addControl() {} fitBounds() {} resize() {} remove() {} on() {} }
  class LngLatBounds { extend() { return this; } }
  return { default: { Map, Marker, Popup, LngLatBounds, NavigationControl: class {} } };
});
import TrackingExperiencePage from './TrackingExperiencePage';

// Synthetic fixture generated by three pure BE functions in services/tracking_experience.py.
// BE source SHA256 b16de691cbac8d37aade70ffa0c76ea35988a1e91d9d779ac1f61d314ee962a5;
// generated fixture SHA256 11cf139b1b505e06209a234d24be6deef197b6af5e8d5fa67238b90e7b580443.
// Portable JSON is test data, not evidence of a live location or production response.
const fixture = fixtureData as Record<string, any>;
const pin = () => '7'.repeat(6); // Own fixture, never a real user's credential.
const markers = (role: string) => seam.markers.filter(marker => !marker.removed && marker.element.className === `marker-${role}`);
const envelope = (status: string, model = 'MunicipioTicket', map = fixture.map,
  location = fixture.location, kind: 'claim' | 'order' = 'claim') => {
  const code = kind === 'order' ? 'MO-42' : model === 'TenantTicket' ? 'T-42' : 'M-42';
  return { kind, contract_version: 'tracking.experience.v1',
    tenant: { id: 51, slug: 'map-fixture' },
    resource: { id: 42, source_model: model, code, subject: 'Expediente sintético', channel: 'web' },
    status: { current_stage: status, label: status }, timeline: [],
    location: structuredClone(location), map: structuredClone(map), support: { enabled: false } };
};
const renderPage = async (body: ReturnType<typeof envelope>) => {
  seam.apiFetch.mockImplementation(async (url: string, options: any) => {
    const parsed = new URL(url, 'https://fixture.invalid');
    expect(parsed.pathname).toBe('/api/public/tracking/experience');
    expect(parsed.searchParams.get('kind')).toBe(body.kind);
    expect(parsed.searchParams.get('code')).toBe(body.resource.code);
    expect(parsed.searchParams.get('tenant_slug')).toBe('map-fixture');
    expect(options).toMatchObject({ skipAuth: true, omitCredentials: true, omitTenant: true,
      omitEntityToken: true, omitChatSessionId: true, isWidgetRequest: true,
      headers: { 'X-Tenant-Slug': 'map-fixture' }, pin: pin() });
    return structuredClone(body);
  });
  let rendered: ReturnType<typeof render> | undefined;
  // Settle the synthetic response and React's lazy retry inside an async act.
  await act(async () => {
    rendered = render(<MemoryRouter initialEntries={[
      `/tracking/${body.kind}/${body.resource.code}?tenant_slug=map-fixture#pin=${pin()}`,
    ]}><Routes><Route path={`/tracking/${body.kind}/:code`} element={<TrackingExperiencePage kind={body.kind} />} /></Routes></MemoryRouter>);
  });
  // These boundaries must pass before attributing any failure to map markers.
  expect(await screen.findByRole('heading', { name: body.kind === 'claim' ? 'Seguimiento de reclamo' : 'Seguimiento de pedido' })).toBeVisible();
  await screen.findByText('Expediente sintético');
  expect(seam.apiFetch).toHaveBeenCalledTimes(1);
  return rendered!;
};

beforeAll(async () => {
  // Preload the ACTUAL component, retaining the synthetic GL engine only.
  // Failure here is an import/setup failure, never a provenance counterexample.
  const actual = await import('@/components/ui/TrackingMap');
  expect(typeof actual.default).toBe('function');
});

beforeEach(() => {
  cleanup(); seam.apiFetch.mockReset(); seam.markers.length = 0; seam.maps.length = 0;
  window.sessionStorage.clear(); window.localStorage.clear();
  HTMLElement.prototype.scrollIntoView = vi.fn();
});
afterEach(() => { cleanup(); vi.restoreAllMocks(); });

describe('reported location provenance through public tracking client and page', () => {
  it.each(['en_proceso', 'asignado', 'validando'])(
    'does not turn the case center into a reported mobile position at %s', async status => {
      expect(fixture.map.center).toEqual({ lat: fixture.location.lat, lng: fixture.location.lng });
      expect(fixture.map.current).toBeUndefined(); expect(fixture.map.driver).toBeUndefined();
      await renderPage(envelope(status)); await screen.findByTestId('tracking-map');
      await waitFor(() => expect(markers('customer')).toHaveLength(1));
      expect(markers('customer')[0].position).toEqual([-68.46, -33.08]);
      expect(screen.queryByText('Posición informada del móvil')).not.toBeInTheDocument();
      expect(markers('driver')).toHaveLength(0);
      expect(seam.apiFetch).toHaveBeenCalledTimes(1);
    });

  it('keeps an explicitly published mobile point distinct from the case destination', async () => {
    const map = { ...fixture.map, current: { lat: -33.09, lng: -68.48 } };
    await renderPage(envelope('en_proceso', 'TenantTicket', map)); await screen.findByTestId('tracking-map');
    await waitFor(() => expect(markers('driver')).toHaveLength(1));
    expect(markers('driver')[0].position).toEqual([-68.48, -33.09]);
    expect(markers('customer')[0].position).toEqual([-68.46, -33.08]);
    expect(screen.getByText('Posición informada del móvil')).toBeInTheDocument();
    expect(seam.apiFetch).toHaveBeenCalledTimes(1);
  });

  it('keeps a valid explicitly published origin without relocating it to the case center', async () => {
    const map = { ...fixture.map, origin: { lat: -33.10, lng: -68.50, name: 'Origen informado' } };
    await renderPage(envelope('recibido', 'MunicipioTicket', map)); await screen.findByTestId('tracking-map');
    await waitFor(() => expect(markers('store')).toHaveLength(1));
    expect(markers('store')[0].position).toEqual([-68.50, -33.10]);
    expect(markers('customer')[0].position).toEqual([-68.46, -33.08]);
    expect(markers('driver')).toHaveLength(0);
    expect(screen.getByText('Origen informado')).toBeInTheDocument();
  });

  it('does not invent a map or coordinates for a case without a published location', async () => {
    await renderPage(envelope('en_proceso', 'TenantTicket', fixture.emptyMap, fixture.emptyLocation));
    await screen.findByText('Expediente sintético');
    await waitFor(() => expect(seam.apiFetch).toHaveBeenCalledTimes(1));
    expect(screen.queryByTestId('tracking-map')).not.toBeInTheDocument();
    expect(screen.queryByText('Posición informada del móvil')).not.toBeInTheDocument();
    expect(seam.markers).toHaveLength(0); expect(seam.maps).toHaveLength(0);
  });

  it('keeps an explicitly published mobile point for a shipped order', async () => {
    const map = { ...fixture.map, driver: { lat: -33.12, lng: -68.52 } };
    await renderPage(envelope('enviado', 'MarketOrder', map, fixture.location, 'order'));
    await screen.findByTestId('tracking-map');
    await waitFor(() => expect(markers('driver')).toHaveLength(1));
    expect(markers('driver')[0].position).toEqual([-68.52, -33.12]);
    expect(markers('customer')[0].position).toEqual([-68.46, -33.08]);
    expect(screen.getByText('Posición informada del móvil')).toBeInTheDocument();
  });

  it('does not let a status string hide an explicitly published driver point', async () => {
    const map = { ...fixture.map, current_status: 'asignado', driver: { lat: -33.13, lng: -68.53 } };
    await renderPage(envelope('asignado', 'TenantTicket', map)); await screen.findByTestId('tracking-map');
    await waitFor(() => expect(markers('driver')).toHaveLength(1));
    expect(markers('driver')[0].position).toEqual([-68.53, -33.13]);
    expect(markers('customer')[0].position).toEqual([-68.46, -33.08]);
  });
});
